/**
 * MiniSoC AES - PLL RTL Mock
 *
 * Reference clock:
 *   i_clk_2ghz = 2 GHz
 *
 * SPI-controlled configuration:
 *   i_enable       : enables the PLL mock
 *   i_div_sel[1:0] : 00 -> /1
 *                    01 -> /2
 *                    10 -> /4
 *                    11 -> /8
 *
 * Output frequencies:
 *   /1 -> 2.000 GHz
 *   /2 -> 1.000 GHz
 *   /4 -> 0.500 GHz
 *   /8 -> 0.250 GHz
 *
 * Lock behavior:
 *   After i_enable rises, the mock waits a pseudo-random number of reference
 *   clock cycles between LOCK_MIN_CYCLES and LOCK_MAX_CYCLES. Then o_locked
 *   is asserted and the selected clock is released to o_clk.
 *
 * Notes:
 *   - Divider configuration is latched when i_enable rises.
 *   - Changes to i_div_sel while enabled are intentionally ignored.
 *   - To change divider: disable -> configure -> enable.
 *   - o_locked is intended to be readable by the SPI front-end.
 *   - The pseudo-random lock delay is generated by an RTL LFSR so the module
 *     does not depend on $urandom for its functional behavior.
 */

module minisoc_pll_mock #(
  parameter int LOCK_MIN_CYCLES = 8,
  parameter int LOCK_MAX_CYCLES = 31
)(
  input  logic       i_clk_2ghz,
  input  logic       rst_n,

  // Configuration from SPI
  input  logic       i_enable,
  input  logic [1:0] i_div_sel,

  // System outputs
  output logic       o_clk,
  output logic       o_locked
);

  localparam int LOCK_RANGE = LOCK_MAX_CYCLES - LOCK_MIN_CYCLES + 1;

  logic [1:0]  div_sel_latched;
  logic [2:0]  div_counter;
  logic [15:0] lfsr;
  logic        enable_d;

  integer unsigned lock_counter;
  integer unsigned lock_target;

  logic raw_div_clk;
  logic clk_gate_en;

  // Basic parameter validation for the mock.
  initial begin
    if (LOCK_MIN_CYCLES < 1)
      $fatal(1, "LOCK_MIN_CYCLES must be >= 1");

    if (LOCK_MAX_CYCLES < LOCK_MIN_CYCLES)
      $fatal(1, "LOCK_MAX_CYCLES must be >= LOCK_MIN_CYCLES");
  end

  // 16-bit maximal-length style LFSR.
  function automatic logic [15:0] lfsr_next(input logic [15:0] value);
    lfsr_next = {value[14:0],
                 value[15] ^ value[13] ^ value[12] ^ value[10]};
  endfunction

  // Lock generation and divider state.
  always_ff @(posedge i_clk_2ghz or negedge rst_n) begin
    if (!rst_n) begin
      div_sel_latched <= 2'b00;
      div_counter     <= 3'b000;
      lfsr            <= 16'h1ACE;
      enable_d        <= 1'b0;
      lock_counter    <= 0;
      lock_target     <= LOCK_MIN_CYCLES;
      o_locked        <= 1'b0;
    end
    else begin
      lfsr     <= lfsr_next(lfsr);
      enable_d <= i_enable;

      if (!i_enable) begin
        // Disabled PLL: no lock and divider is held in a known phase.
        o_locked        <= 1'b0;
        lock_counter    <= 0;
        div_counter     <= 3'b000;

        // Allow software to program the next divider while disabled.
        div_sel_latched <= i_div_sel;
      end
      else if (!enable_d) begin
        // Rising edge of enable: latch configuration and choose lock delay.
        div_sel_latched <= i_div_sel;
        lock_counter    <= 0;
        lock_target     <= LOCK_MIN_CYCLES + (lfsr % LOCK_RANGE);
        o_locked        <= 1'b0;
        div_counter     <= 3'b000;
      end
      else if (!o_locked) begin
        // PLL acquisition time.
        div_counter <= 3'b000;

        if (lock_counter == (lock_target - 1)) begin
          o_locked     <= 1'b1;
          lock_counter <= lock_counter;
        end
        else begin
          lock_counter <= lock_counter + 1;
        end
      end
      else begin
        // Locked: divider becomes active.
        div_counter <= div_counter + 3'b001;
      end
    end
  end

  // Frequency selection.
  always_comb begin
    unique case (div_sel_latched)
      2'b00: raw_div_clk = i_clk_2ghz;    // /1
      2'b01: raw_div_clk = div_counter[0]; // /2
      2'b10: raw_div_clk = div_counter[1]; // /4
      2'b11: raw_div_clk = div_counter[2]; // /8
      default: raw_div_clk = 1'b0;
    endcase
  end

  // Gate control changes only while the reference clock is low.
  // This avoids releasing/stopping the system clock in the middle of a high
  // pulse in this RTL mock.
  always_ff @(negedge i_clk_2ghz or negedge rst_n) begin
    if (!rst_n)
      clk_gate_en <= 1'b0;
    else
      clk_gate_en <= i_enable && o_locked;
  end

  assign o_clk = clk_gate_en ? raw_div_clk : 1'b0;

endmodule
